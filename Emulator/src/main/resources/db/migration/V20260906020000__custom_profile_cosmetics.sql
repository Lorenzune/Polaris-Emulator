-- Custom Profile Cosmetics (Backgrounds, Stands, Cards, Borders, Poses) Categories & Catalog Setup

CREATE TABLE IF NOT EXISTS `custom_profile_cosmetic_categories` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `category_type` enum('background','stand','card','border','pose','slot') NOT NULL DEFAULT 'background',
  `name` varchar(100) NOT NULL,
  `badge` varchar(50) NOT NULL DEFAULT '',
  `sort_order` int(11) NOT NULL DEFAULT 0,
  `enabled` tinyint(1) NOT NULL DEFAULT 1,
  PRIMARY KEY (`id`),
  KEY `idx_category_type` (`category_type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `custom_profile_cosmetics_catalog` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `category` enum('background','stand','card','border','pose','slot') NOT NULL DEFAULT 'background',
  `category_id` int(11) NOT NULL DEFAULT 1,
  `image_file` varchar(255) NOT NULL,
  `display_name` varchar(150) NOT NULL,
  `cost_credits` int(11) NOT NULL DEFAULT 0,
  `cost_points` int(11) NOT NULL DEFAULT 0,
  `points_type` int(11) NOT NULL DEFAULT 0,
  `min_rank` int(11) NOT NULL DEFAULT 1,
  `is_hc_only` tinyint(1) NOT NULL DEFAULT 0,
  `is_free` tinyint(1) NOT NULL DEFAULT 0,
  `enabled` tinyint(1) NOT NULL DEFAULT 1,
  `sort_order` int(11) NOT NULL DEFAULT 0,
  `created_at` timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_category` (`category`),
  KEY `idx_category_id` (`category_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `users_profile_cosmetics` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `user_id` int(11) NOT NULL,
  `item_id` int(11) NOT NULL,
  `category` varchar(50) NOT NULL,
  `created_at` timestamp NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `user_item_category_unique` (`user_id`,`item_id`,`category`),
  KEY `idx_user_id` (`user_id`),
  KEY `idx_item_id` (`item_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

